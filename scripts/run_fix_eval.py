"""Evaluate Bug Resolution (fixing) on every bug the agent reproduced. Resumable.

Input  : the accepted reproduction test from results/<bench>/<id>.full.json (or .full_v2.json when
         `full` did not reproduce the bug). Fixing is only attempted after a reproduction.
Scoring: (evaluation only, never shown to the agent)
  plausible = the agent accepted its patch (repro test passes, related tests do not regress)
  correct   = plausible AND the hidden oracle (benchmarks/*/oracle_checks.py) passes on the patched tree

  python scripts/run_fix_eval.py --modes fix_full fix_single fix_no_repro
  python scripts/run_fix_eval.py --summary
"""
from __future__ import annotations

import argparse
import json
import sys
import traceback
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from reproagent.agent import FIX_MODES, AgentConfig, ReproAgent  # noqa: E402
from reproagent.llm import DEFAULT_MODEL, LLM  # noqa: E402
from reproagent.models import BugReport, BugSpec, ReproTest  # noqa: E402
from reproagent.report import save_fix  # noqa: E402
from reproagent.verification import run_python_check  # noqa: E402

BENCHES = {
    "shopcart": (ROOT / "benchmarks/shopcart/bugs.json", ROOT / "benchmarks/shopcart/work",
                 ROOT / "benchmarks/shopcart"),
    "bugsinpy": (ROOT / "benchmarks/bugsinpy/manifest.json", ROOT / "benchmarks/bugsinpy/work",
                 ROOT / "benchmarks/bugsinpy"),
    "multiloc": (ROOT / "benchmarks/multiloc/bugs.json", ROOT / "benchmarks/multiloc/work",
                 ROOT / "benchmarks/multiloc"),
}
RESULTS = ROOT / "results"
OUT = RESULTS / "fix"


def load_oracles(d: Path) -> dict:
    ns: dict = {}
    exec((d / "oracle_checks.py").read_text(encoding="utf-8"), ns)
    return ns["ORACLES"]


def repro_for(bench: str, bid: str) -> dict | None:
    for mode in ("full", "full_v2"):
        p = RESULTS / bench / f"{bid}.{mode}.json"
        if p.exists():
            o = json.loads(p.read_text(encoding="utf-8"))
            if o["verdict"] == "reproduced" and o["final_test"]:
                o["_from"] = mode
                return o
    return None


def run(benches: list[str], modes: list[str], only: list[str] | None, model: str) -> None:
    llm = LLM(model)
    for bench in benches:
        manifest, work, bdir = BENCHES[bench]
        bugs = json.loads(manifest.read_text(encoding="utf-8"))["bugs"]
        oracles = load_oracles(bdir)
        shims = [str(ROOT / "benchmarks/bugsinpy/compat_shims")] if bench == "bugsinpy" else []
        agent = ReproAgent(llm, AgentConfig(extra_paths=shims), log=lambda s: print("    " + s, flush=True))
        for b in bugs:
            if b.get("excluded") or b.get("expected_verdict") or (only and b["id"] not in only):
                continue
            o = repro_for(bench, b["id"])
            if o is None:
                continue
            for mode in modes:
                dest = OUT / bench / f"{b['id']}.{mode}.json"
                if dest.exists():
                    continue
                print(f"== [{bench}] {b['id']} {mode} (repro test from `{o['_from']}`)", flush=True)
                report = BugReport(b["id"], b["title"], b["body"], bench)
                spec = BugSpec(**o["spec"])
                test = ReproTest(len(o["attempts"]), o["final_test"])
                try:
                    f = agent.fix(report, spec, work / b["id"] / "buggy", test,
                                  o["attempts"][-1]["execution"]["output"], mode=mode)
                    final = next((a.patch for a in reversed(f.attempts) if a.check.accepted), None)
                    if final is not None:   # hidden oracle on the patched tree
                        ok, out = run_python_check(work / b["id"] / "buggy", final.files, oracles[b["id"]],
                                                   extra_paths=shims)
                        f.correct, f.eval_output = ok, out
                        f.no_regression = True
                    else:
                        f.correct = False
                    rec = f.to_dict()
                    rec["repro_from"] = o["_from"]
                    rec["repro_valid"] = bool(o.get("fail_to_pass"))
                    save_fix(f, OUT / bench)
                    dest.write_text(json.dumps(rec, indent=2), encoding="utf-8")
                    print(f"   -> {f.status} correct={f.correct} {f.total_time_s}s", flush=True)
                except Exception:   # keep the batch going
                    traceback.print_exc()
    summarize()


def summarize() -> None:
    lines = ["# Bug resolution (fixing) summary (auto-generated by scripts/run_fix_eval.py)", "",
             "Fixing is attempted only for bugs with an accepted reproduction test. "
             "*Plausible* = the agent's own validation accepted the patch (reproduction test passes, related "
             "existing tests do not regress). *Correct* = plausible and the hidden oracle passes.", ""]
    rows = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(OUT.glob("*/*.json"))] if OUT.exists() else []
    if not rows:
        print("no results")
        return
    for p, r in zip(sorted(OUT.glob("*/*.json")), rows):
        r["bench"] = p.parent.name
    lines += ["| mode | bench | bugs | plausible | **correct** | plausible but wrong | avg patch attempts | "
              "avg SLM calls | avg time (s) |", "|---|---|---|---|---|---|---|---|---|"]
    avg = lambda xs: (sum(xs) / len(xs)) if xs else 0  # noqa: E731
    for mode in FIX_MODES:
        for bench in ("shopcart", "bugsinpy", "single-location", "multiloc"):
            rs = [r for r in rows if r["mode"] == mode and (r["bench"] == bench or (
                bench == "single-location" and r["bench"] != "multiloc"))]
            if not rs:
                continue
            pl = sum(r["status"] == "fixed" for r in rs)
            co = sum(bool(r["correct"]) for r in rs)
            name = f"**{bench}**" if bench in ("single-location", "multiloc") else bench
            lines.append(f"| {mode} | {name} | {len(rs)} | {pl} | **{co} ({co / len(rs):.0%})** | {pl - co} | "
                         f"{avg([len(r['attempts']) for r in rs]):.1f} | {avg([r['llm_calls'] for r in rs]):.1f} | "
                         f"{avg([r['total_time_s'] for r in rs]):.0f} |")
    modes = [m for m in FIX_MODES if any(r["mode"] == m for r in rows)]
    lines += ["", "Per bug (C = correct, P = plausible but fails the hidden oracle, X = no accepted patch; "
              "number = patch attempts; repro = where the reproduction test came from, FP = it was a false-positive "
              "reproduction):", "", "| bug | repro | " + " | ".join(modes) + " | categories (fix_full) |",
              "|---" * (len(modes) + 3) + "|"]
    cell = {(r["bug_id"], r["mode"]): r for r in rows}
    for bid in sorted({r["bug_id"] for r in rows}):
        any_r = next(r for r in rows if r["bug_id"] == bid)
        cs = []
        for m in modes:
            r = cell.get((bid, m))
            if r is None:
                cs.append("-")
            else:
                tag = "C" if r["correct"] else ("P" if r["status"] == "fixed" else "X")
                cs.append(f"{tag} ({len(r['attempts'])})")
        ff = cell.get((bid, "fix_full"))
        cats = ", ".join(a["check"]["category"] for a in ff["attempts"]) if ff else ""
        rep = any_r.get("repro_from", "?") + ("" if any_r.get("repro_valid") else ", FP")
        lines.append(f"| {bid} | {rep} | " + " | ".join(cs) + f" | {cats} |")
    cats = defaultdict(int)
    for r in rows:
        if r["mode"] == "fix_full":
            for a in r["attempts"]:
                cats[a["check"]["category"]] += 1
    lines += ["", "Patch attempt categories in `fix_full`: " + ", ".join(f"{k}={v}" for k, v in sorted(cats.items())), ""]
    (RESULTS / "FIX_SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", nargs="+", default=list(BENCHES), choices=list(BENCHES))
    ap.add_argument("--modes", nargs="+", default=list(FIX_MODES))
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--summary", action="store_true")
    a = ap.parse_args()
    if a.summary:
        summarize()
    else:
        run(a.bench, a.modes, a.only, a.model)
