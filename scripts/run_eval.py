"""Run ReproAgent and its baselines over a benchmark; results are resumable.

  python scripts/run_eval.py --bench shopcart --modes full no_context single_shot baseline
  python scripts/run_eval.py --bench bugsinpy --modes full baseline
  python scripts/run_eval.py --summary            # (re)build results/SUMMARY.md only
"""
from __future__ import annotations

import argparse
import json
import sys
import traceback
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from reproagent.agent import MODES, AgentConfig, ReproAgent  # noqa: E402
from reproagent.llm import DEFAULT_MODEL, LLM  # noqa: E402
from reproagent.models import BugReport  # noqa: E402
from reproagent.report import save  # noqa: E402

BENCHES = {
    "shopcart": (ROOT / "benchmarks/shopcart/bugs.json", ROOT / "benchmarks/shopcart/work"),
    "bugsinpy": (ROOT / "benchmarks/bugsinpy/manifest.json", ROOT / "benchmarks/bugsinpy/work"),
    "multiloc": (ROOT / "benchmarks/multiloc/bugs.json", ROOT / "benchmarks/multiloc/work"),
}
RESULTS = ROOT / "results"


def run(bench: str, modes: list[str], only: list[str] | None, budget: int, model: str) -> None:
    manifest, work = BENCHES[bench]
    bugs = json.loads(manifest.read_text(encoding="utf-8"))["bugs"]
    llm = LLM(model)
    out_dir = RESULTS / bench
    for mode in modes:
        shims = [str(ROOT / "benchmarks/bugsinpy/compat_shims")] if bench == "bugsinpy" else None
        agent = ReproAgent(llm, AgentConfig(mode=mode, budget=budget, extra_paths=shims),
                           log=lambda s: print("    " + s, flush=True))
        for b in bugs:
            if b.get("excluded") or (only and b["id"] not in only):
                continue
            if (out_dir / f"{b['id']}.{mode}.json").exists():
                continue
            print(f"== [{bench}] {b['id']} mode={mode}", flush=True)
            report = BugReport(id=b["id"], title=b["title"], body=b["body"], source=bench)
            try:
                o = agent.run(report, work / b["id"] / "buggy", work / b["id"] / "fixed")
                save(o, out_dir)
                print(f"   -> {o.verdict.value} f2p={o.fail_to_pass} {o.total_time_s}s", flush=True)
            except Exception:  # keep the batch going; record the crash
                traceback.print_exc()
    summarize()


def summarize() -> None:
    lines = ["# Evaluation summary (auto-generated by scripts/run_eval.py)", ""]
    for bench in BENCHES:
        d = RESULTS / bench
        rows = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(d.glob("*.json"))] if d.exists() else []
        if not rows:
            continue
        manifest = json.loads(BENCHES[bench][0].read_text(encoding="utf-8"))["bugs"]
        expected_na = {b["id"] for b in manifest if b.get("expected_verdict")}
        by_mode = defaultdict(list)
        for r in rows:
            by_mode[r["mode"]].append(r)
        lines += [f"## {bench}", "",
                  "Reproducible bugs only (vague/NEEDS-INFO reports excluded from these columns).", "",
                  "| mode | bugs | claimed reproduced | **valid (fail-to-pass)** | valid by meaning | false positives | "
                  "avg attempts | avg SLM calls | avg time (s) | avg time to valid (s) |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for mode in MODES:
            rs = [r for r in by_mode.get(mode, []) if r["bug_id"] not in expected_na]
            if not rs:
                continue
            n = len(rs)
            claimed = sum(r["verdict"] == "reproduced" for r in rs)
            valid = [r for r in rs if r["fail_to_pass"]]
            meaning = sum(bool(r.get("fail_to_pass_semantic", r["fail_to_pass"])) for r in rs)
            fp = claimed - len(valid)
            avg = lambda xs: (sum(xs) / len(xs)) if xs else 0  # noqa: E731
            lines.append(
                f"| {mode} | {n} | {claimed} ({claimed / n:.0%}) | **{len(valid)} ({len(valid) / n:.0%})** | "
                f"{meaning} ({meaning / n:.0%}) | {fp} | "
                f"{avg([len(r['attempts']) for r in rs]):.1f} | {avg([r['llm_calls'] for r in rs]):.1f} | "
                f"{avg([r['total_time_s'] for r in rs]):.0f} | {avg([r['total_time_s'] for r in valid]):.0f} |")
        # per-bug matrix
        ids = sorted({r["bug_id"] for r in rows})
        modes = [m for m in MODES if m in by_mode]
        lines += ["", "Per-bug outcome (V = valid reproduction, Vm = valid by meaning only (error-message wording differs, "
                  "same meaning), FP = claimed but fails fail-to-pass check, "
                  "NR = not reproduced, NI = needs more information):", "",
                  "| bug | " + " | ".join(modes) + " |", "|---" * (len(modes) + 1) + "|"]
        cell = {(r["bug_id"], r["mode"]): r for r in rows}
        for i in ids:
            cs = []
            for m in modes:
                r = cell.get((i, m))
                if r is None:
                    cs.append("-")
                elif r["fail_to_pass"]:
                    cs.append(f"V ({len(r['attempts'])})")
                elif r.get("fail_to_pass_semantic"):
                    cs.append("Vm")
                elif r["verdict"] == "reproduced":
                    cs.append("FP")
                elif r["verdict"] == "needs_more_information":
                    cs.append("NI")
                else:
                    cs.append("NR")
            lines.append(f"| {i} | " + " | ".join(cs) + " |")
        # failure categories over all attempts of full mode
        cats = defaultdict(int)
        for r in by_mode.get("full", []):
            for a in r["attempts"]:
                cats[a["analysis"]["category"]] += 1
        if cats:
            lines += ["", "Attempt outcome categories in `full` mode: " +
                      ", ".join(f"{k}={v}" for k, v in sorted(cats.items())), ""]
        lines.append("")
    (RESULTS / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", choices=list(BENCHES))
    ap.add_argument("--modes", nargs="+", default=list(MODES))
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--budget", type=int, default=4)
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--summary", action="store_true")
    a = ap.parse_args()
    if a.summary or not a.bench:
        summarize()
    else:
        run(a.bench, a.modes, a.only, a.budget, a.model)
